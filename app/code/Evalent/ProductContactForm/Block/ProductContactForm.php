<?php

declare(strict_types=1);

namespace Evalent\ProductContactForm\Block;

use Evalent\ProductContactForm\Helper\Data;
use \Magento\Catalog\Block\Product\Context;
use Magento\Widget\Block\BlockInterface;

class ProductContactForm extends \Magento\Catalog\Block\Product\AbstractProduct implements BlockInterface
{

    /**
     * @var \Evalent\ProductContactForm\Helper\Data
     */
    private $dataHelper;

    protected $_storeManager;

    public function __construct(
        Data $dataHelper,
        Context $context,
        \Magento\Store\Model\StoreManagerInterface $storeManager,
        array $data = []
    ) {
        parent::__construct($context, $data);
        $this->dataHelper = $dataHelper;
        $this->_storeManager = $storeManager;
    }

    protected function _toHtml()
    {
        if (!$this->dataHelper->isEnabled()) {
            return '';
        }
        return parent::_toHtml(); // TODO: Change the autogenerated stub
    }

    /**
     * @return string
     */
    public function getFormAction()
    {
        return $this->getUrl('contact/product/post');
    }

    public function isRecaptchaEnabled(): bool
    {
        return $this->dataHelper->isRecaptchaEnabled();
    }

    public function isGRecaptchaEnabled(): bool
    {
        return $this->dataHelper->isGRecaptchaEnabled();
    }

    public function getStoreCode()
    {
        return $this->_storeManager->getStore()->getCode();
    }

    protected function _prepareLayout()
    {
        parent::_prepareLayout();

        if($this->isGRecaptchaEnabled()) {
            $this->addChild(
                'recaptcha',
                'Magento\ReCaptchaUi\Block\ReCaptcha',
                [
                    'recaptcha_for' => 'productcontactform',
                    'template' => 'Magento_ReCaptchaFrontendUi::recaptcha.phtml',
                    'jsLayout' => [
                        'components' => [
                            'recaptcha' => [
                                'component' => 'Magento_ReCaptchaFrontendUi/js/reCaptcha',
                                'reCaptchaId' => 'recaptcha-product-contact'
                            ]
                        ]
                    ]
                ]
            );
        }

        return $this;
    }

}
