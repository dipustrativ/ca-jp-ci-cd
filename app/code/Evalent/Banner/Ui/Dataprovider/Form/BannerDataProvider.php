<?php

declare(strict_types=1);

namespace Evalent\Banner\Ui\Dataprovider\Form;

use Evalent\Banner\Model\Banner\DataProvider;
use Evalent\Banner\Model\UploaderPool;
use Magento\Framework\App\ObjectManager;
use Magento\Framework\App\Request\DataPersistorInterface;
use Magento\Framework\App\RequestInterface;
use Magento\Framework\UrlInterface;
use Magento\Ui\DataProvider\AbstractDataProvider;
use Evalent\Banner\Model\ResourceModel\Banner\CollectionFactory;
use Magento\Ui\DataProvider\Modifier\ModifierInterface;
use Magento\Ui\DataProvider\Modifier\PoolInterface;

class BannerDataProvider extends \Magento\Ui\DataProvider\AbstractDataProvider
{

    const KEY_SUBMIT_URL = 'submit_url';


    /**
     * @var \Magento\Ui\DataProvider\Modifier\PoolInterface
     */
    private $modifiersPool;

    /**
     * @var \Magento\Framework\UrlInterface
     */
    private $urlBuilder;

    /**
     * @var \Evalent\Banner\Model\UploaderPool
     */
    private $uploaderPool;

    /**
     * @var \Magento\Framework\App\Request\DataPersistorInterface
     */
    private $dataPersistor;

    /**
     * @var \Magento\Framework\App\RequestInterface
     */
    private $request;

    protected $loadedData;

    public function __construct(
        $name,
        $primaryFieldName,
        $requestFieldName,
        CollectionFactory $collectionFactory,
        UploaderPool $uploaderPool,
        DataPersistorInterface $dataPersistor,
        UrlInterface $urlBuilder,
        RequestInterface $request,
        array $meta = [],
        array $data = [],
        ?PoolInterface $modifiersPool = null
    ) {
        $this->collection = $collectionFactory->create();
        parent::__construct($name, $primaryFieldName, $requestFieldName, $meta,
            $data);
        $this->modifiersPool = $modifiersPool;
        $this->urlBuilder = $urlBuilder;
        $this->uploaderPool = $uploaderPool;
        $this->dataPersistor = $dataPersistor;
        $this->request = $request;
    }

    public function getData()
    {
        if (isset($this->loadedData)) {
            return $this->loadedData;
        }
        $this->loadedData = [];
        $storeId = (int) $this->request->getParam('store');
        $this->collection->addFieldToSelect('*');
        $this->collection->setStore($storeId);
        $items = $this->collection->getItems();
        foreach ($items as $model) {
            $data = $model->getData();
            $uploader = $this->uploaderPool->getUploader('image');
            if (isset($data['desktop_image']) && $data['desktop_image']) {
                $img = [];
                $img[0]['image'] = $data['desktop_image'];
                $img[0]['url'] = $uploader->getBaseUrl() . $uploader->getBasePath(). $data['desktop_image'];
                $data['desktop_image'] = $img;
            }
            if (isset($data['mobile_image']) && $data['mobile_image']) {
                $img = [];
                $img[0]['image'] = $data['mobile_image'];
                $img[0]['url'] = $uploader->getBaseUrl() . $uploader->getBasePath(). $data['mobile_image'];
                $data['mobile_image'] = $img;
            }
            $this->loadedData[$model->getId()] = $data;
        }
        $data = $this->dataPersistor->get('evalent_banner_banner_entity');

        if (!empty($data)) {
            $model = $this->collection->getNewEmptyItem();
            $model->setData($data);
            $this->loadedData[$model->getId() ?? ''] = $model->getData();
            $this->dataPersistor->clear('evalent_banner_banner_entity');
        }

        if (isset($model)) {
            $parameters = [
                'entity_id' => $model->getEntityId(),
                'store' => $storeId,
            ];
            $submitUrl = $this->urlBuilder->getUrl('evalent_banner/banner/save', $parameters);

            $this->data = array_replace_recursive(
                $this->data,
                [
                    'config' => [
                        self::KEY_SUBMIT_URL => $submitUrl,
                    ]
                ]
            );
        }

        return $this->loadedData;
    }

    public function addFilter(\Magento\Framework\Api\Filter $filter)
    {
        parent::addFilter($filter); // TODO: Change the autogenerated stub
    }

    /**
     * @inheritdoc
     * @since 103.0.0
     */
    public function getMeta()
    {
        $meta = parent::getMeta();
        /** @var ModifierInterface $modifier */
        foreach ($this->modifiersPool->getModifiersInstances() as $modifier) {
            $meta = $modifier->modifyMeta($meta);
        }

        return $meta;
    }
}
